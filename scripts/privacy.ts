/**
 * The privacy guard: this repository is public, so no file may carry the
 * product's private details (decision numbers, plan sections, database
 * internals, the private repository's name, people's real names or
 * addresses, private hostnames, the product team's own project key).
 *
 *   npm run privacy        scan every file git knows (tracked or new, not ignored)
 *
 * test/privacy.test.ts runs the same scan, and checks every rule against
 * its own examples. To extend the guard, add a rule to RULES (with an
 * example it must catch and one it must not), or an entry to the allow
 * lists below. Patterns are written so that this file doesn't match itself
 * (for example `K[e]lly`), and the examples are assembled from pieces.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface Rule {
  id: string;
  /** What the rule keeps out, for the report. */
  why: string;
  /** Global regular expression; every match is a finding unless allowed. */
  pattern: RegExp;
  /** Matches that are fine in some files: the file path and the text around the match. */
  allow?: { path: RegExp; text: RegExp }[];
  /** Further check of a match: return false to let it pass. */
  forbidden?: (match: RegExpExecArray) => boolean;
  /** Texts the rule must catch, and texts it must let pass (the self-test). */
  examples: { hit: string[]; miss?: string[] };
}

/** Files never scanned (third-party or generated by npm). */
export const EXCLUDED: RegExp[] = [/^package-lock\.json$/, /(^|\/)node_modules\//, /^dist\//];

/** Email domains for made-up people. */
export const ALLOWED_EMAIL_DOMAINS = ['example.com', 'example.org', 'example.net'];

/** Public addresses that may appear: the security contact and the commit trailer. */
