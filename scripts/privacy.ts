export interface Finding {
  file: string;
  line: number;
  rule: string;
  match: string;
}

function allowed(rule: Rule, file: string, text: string, index: number): boolean {
  return (rule.allow ?? []).some((a) => {
    if (!a.path.test(file)) return false;
    const around = text.slice(Math.max(0, index - 100), index + 100);
    return a.text.test(around);
  });
}

/** The findings in one text, as if it were the file `file` (a path with forward slashes). */
export function scanText(file: string, text: string, rules: readonly Rule[] = RULES): Finding[] {
  const out: Finding[] = [];
  for (const rule of rules) {
    const pattern = new RegExp(rule.pattern.source, rule.pattern.flags);
    for (let m = pattern.exec(text); m !== null; m = pattern.exec(text)) {
      if (m[0].length === 0) pattern.lastIndex++;
      if (rule.forbidden && !rule.forbidden(m)) continue;
      if (allowed(rule, file, text, m.index)) continue;
      const line = text.slice(0, m.index).split('\n').length;
      out.push({ file, line, rule: rule.id, match: m[0] });
    }
  }
  return out;
}

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Every file git knows (tracked, or new and not ignored); without git, every file on disk. */
export function repoFiles(root: string = ROOT): string[] {
  let files: string[];
  try {
    files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .split('\0')
      .filter(Boolean);
  } catch {
    files = [];
    const walk = (dir: string): void => {
      for (const name of readdirSync(dir)) {
        if (name === '.git' || name === 'node_modules' || name === 'dist') continue;
        const full = join(dir, name);
        if (statSync(full).isDirectory()) walk(full);
        else files.push(relative(root, full).split(sep).join('/'));
      }
    };
    walk(root);
  }
  return [...new Set(files)].filter((f) => !EXCLUDED.some((e) => e.test(f))).sort();
}

/** Scans the repository. */
export function scanRepo(root: string = ROOT): Finding[] {
  const out: Finding[] = [];
  for (const file of repoFiles(root)) {
    let buffer: Buffer;
    try {
      buffer = readFileSync(join(root, file));
    } catch {
      continue; // deleted but not yet staged
    }
    if (buffer.includes(0)) continue; // binary
    out.push(...scanText(file, buffer.toString('utf8')));
  }
  return out;
}

/** Runs each rule on its own examples; returns what went wrong. */
export function selfTest(rules: readonly Rule[] = RULES): string[] {
  const problems: string[] = [];
  for (const rule of rules) {
    for (const hit of rule.examples.hit) {
      if (!scanText('example.md', hit, [rule]).length) problems.push(`${rule.id} misses "${hit}"`);
    }
    for (const miss of rule.examples.miss ?? []) {
      if (scanText('example.md', miss, [rule]).length) problems.push(`${rule.id} flags "${miss}"`);
    }
  }
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const problems = selfTest();
  const findings = scanRepo();
  for (const p of problems) console.error(`self-test: ${p}`);
  for (const f of findings) {
    const why = RULES.find((r) => r.id === f.rule)?.why ?? '';
    console.error(`${f.file}:${f.line}: ${f.rule} (${why}): ${f.match}`);
  }
  if (problems.length + findings.length > 0) {
    console.error(
      `Privacy guard: ${findings.length} finding(s), ${problems.length} self-test problem(s).`,
    );
    process.exit(1);
  }
  console.log(`Privacy guard: ${repoFiles().length} files clean.`);
}
